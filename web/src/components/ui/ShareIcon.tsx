type Props = {
  name: ShareIconName;
  /** Whole pixels only (rule: icons stay crisp on scaled screens). */
  size?: 20 | 24 | 28;
  /** "theme" look only: a white square behind the icon, for black buttons where an ink outline would disappear. */
  tile?: boolean;
  className?: string;
};

export function ShareIcon({ name, size = 24, tile = false, className }: Props) {
  if (SHARE_ICON_STYLE === "theme") {
    return (
      <span className={cx(tile ? styles.tile : styles.plain, className)}>
        <svg width={size} height={size} viewBox="0 0 48 48" fill="none" strokeWidth={3.5} aria-hidden="true" className={styles.svg}>
          <ThemedGlyph name={name} />
        </svg>
      </span>
    );
  }
  if (name === "link") {
    return (
      <span className={cx(styles.plain, className)}>
        <span className={styles.linkMask} style={{ width: size, height: size }} aria-hidden="true" />
      </span>
    );
  }
  const glyph = GLYPHS[name];
  return (
    <span className={cx(styles.plain, className)}>
      <svg width={size} height={size} viewBox="0 0 48 48" fill="currentColor" aria-hidden="true" className={styles.svg}>
        <path d={glyph.d} fillRule={glyph.evenOdd ? "evenodd" : undefined} clipRule={glyph.evenOdd ? "evenodd" : undefined} />
      </svg>
    </span>
  );
}
